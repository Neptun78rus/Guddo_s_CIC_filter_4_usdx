#ifndef SDR_RX_FIXED_H
#define SDR_RX_FIXED_H

#include <stdint.h>

/* =========================================================================
 * 12-битный АЦП без перехода на int32_t + uDSC (LGT8F328P)
 *
 * ГЛАВНОЕ: середина 12-битного АЦП — 2048, а НЕ 512!
 *   ac = (int16_t)ADC12 - ADC_MID;   // ADC_MID = 2048 -> диапазон ±2047
 * Состояния CIC остаются int16_t; промежуточные суммы считаются локальным
 * int32 (регистры, не RAM) + sat16() — это и есть защита от «тишины».
 * Полный код: sdr_rx_12bit.c.
 *
 * Запасной вариант (минимальная диффа, если тело CIC трогать нельзя):
 *   ac = (ADC12 >> 2) - 512   -> ровно тот же int16 диапазон, что и раньше,
 *                                ни одна константа в теле CIC не меняется,
 *                                НО теряется 2 бита разрешения (-12 дБ).
 * Либо то же самое аппаратно через uDSC:
 *   ac = uDSC_div_u16(raw, 4) - 512;
 *
 * uDSC: 32-битный HW умножитель/делитель LGT8F328P.
 * Регистры (APB-область, см. референс-мануал LGT8F328P, гл. uDSC):
 *   DSC_CON  - управление/статус (GO, READY, режим MUL_DIV32)
 *   DSC_AL/AH, DSC_BL/BH - операнды A,B (16 бит каждый в нашем режиме)
 *   DSC_CL..CH - делимое (32 бит), DSC_LL..LH - частное/произведение (32 бита)
 * ========================================================================= */

/* --- карты регистров uDSC (адреса из референса LGT8F328P) -------------- */
#if defined(LGT8F328P)
#define REG_DSC_CON   (*(volatile uint8_t *)0x8B4)
#define REG_DSC_AL    (*(volatile uint8_t *)0x8B5)
#define REG_DSC_AH    (*(volatile uint8_t *)0x8B6)
#define REG_DSC_BL    (*(volatile uint8_t *)0x8B7)
#define REG_DSC_BH    (*(volatile uint8_t *)0x8B8)
#define REG_DSC_LL    (*(volatile uint8_t *)0x8BD)
#define REG_DSC_LH    (*(volatile uint8_t *)0x8BE)
#define DSC_GO        0x80   // st: запустить операцию
#define DSC_READY     0x80   // ld: операция завершена
#define DSC_MODE_MULDIV 0x00 // режим 32-битного MUL/DIV
#endif

/* --- прототипы ---------------------------------------------------------- */
void      uDSC_init(void);
int32_t   uDSC_mul_i16(int16_t a, int16_t b);       // a*b за ~несколько тактов
uint16_t  uDSC_div_u16(uint16_t num, uint16_t den); // целочисленное деление

/* Центрирование входа: единая точка правды под разрешение АЦП.
 * Меняем ТОЛЬКО здесь — остальной код не знает о ширине АЦП.
 *
 * ВАРИАНТ A (рекомендуется, см. sdr_rx_12bit.c): полная 12-битная
 * точность, середина 2048, состояния int16 + насыщение sat16:
 *   return (int16_t)raw - ADC_MID;   // ADC_MID = 2048
 *
 * ВАРИАНТ B (минимальная диффа, если нельзя трогать тело CIC):
 * нормализовать масштаб на входе, ни одна константа в фильтре не
 * меняется, но теряется 2 бита разрешения (-12 дБ динамического):     */
#define ADC_BITS    12
#define ADC_MID     (1 << (ADC_BITS - 1))     /* 2048 для 12 бит, НЕ 512 */
#define ADC_HALF_SHIFT 2                       /* только для варианта B */

static inline int16_t adc_center(uint16_t raw)
{
#if defined(FULL_12BIT)
    return (int16_t)raw - ADC_MID;             /* вариант A: ±2047, sat16 обязателен */
#else
    return (int16_t)((raw >> ADC_HALF_SHIFT) - (ADC_MID >> ADC_HALF_SHIFT));
    /* вариант B: эквивалентно старому "- 512" при 12 битах               */
#endif
}

/* CIC N=3, L=2, M_SR=1: состояния остаются int16_t.
 * Защита от переполнения второй секции — насыщение (sat16),
 * дешевле и предсказуемее, чем wrap-around, который и давал «тишину».  */
static inline int16_t sat16(int32_t v)
{
    if (v >  32767) return  32767;
    if (v < -32768) return -32768;
    return (int16_t)v;
}

/* Второй каскад: сумма коэффициентов 1+3+3+1 = 8 максимумов по ±1023*...
 * Посчитаем промежуточный результат в int32 локально (регистры, не RAM),
 * затем saturate -> int16. Локальный int32 на AVR компилируется в пару
 * addadc/subadc и не тянет библиотечных вызовов, т.к. нет умножений.    */

#endif // SDR_RX_FIXED_H
