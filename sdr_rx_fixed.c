/* --- 1) sdr_rx_common_i()/sdr_rx_common_q(): единственная правка --------
 *
 * БЫЛО:
 *   return (int16_t)ADC_read(...) - 512;          // середина 10 бит
 * СТАЛО — СЕРЕДИНА 2048, а не 512 (!):
 *   return adc_center(ADC_read(...));             // ADC_BITS=12 -> ADC_MID=2048
 *
 * ВАРИАНТ A (рекомендуется, полная 12-бит точность, см. sdr_rx_12bit.c):
 *   ac = (int16_t)raw - 2048;                     // ±2047, все LSB сохранены
 *   + sat16() на каждом промежуточном сумматоре CIC (замена wrap-around).
 * ВАРИАНТ B (если тело CIC трогать нельзя вообще):
 *   ac = (raw >> 2) - 512;                        // масштаб к старому, но теряем 2 бита
 *
 * Всё остальное в теле CIC остаётся нетронутым кроме sat16/сдвига ac2.
 */

/* --- 2) Опционально: сохранить 12-битную точность без int32 состояний ---
 *
 * Если >>2 неприемлем (теряем SNR 6 дБ), держим состояния в "условных
 * 12 битах", а произведение на коэффициенты и сдвиг считаем uDSC:
 *
 *   ac = (int16_t)raw - 2048;                     // полный диапазон ±2048
 *   // вторая секция, было: (za0 + (za1+zb0)*3 + zb1) >> M_SR
 *   // стало: sum*3 через uDSC_mul_i16 -> результат гарантированно в i32,
 *   // затем sat16() возвращает в i16. Никаких 32-битных переменных в RAM:
 *
 *   int32_t t = uDSC_mul_i16((int16_t)(i_s1za1 + i_s1zb0), 3); // HW mul
 *   i_s1zb1_new = sat16(((int32_t)i_s1za0 + t + i_s1zb1) >> M_SR);
 *
 * Но учтите: сумма (i_s1za1 + i_s1zb0) при ±2048 даёт ±4096 — влезает в
 * int16; произведение ×3 = ±12288 — считает uDSC; итоговая сумма до
 * ±~20000 — до сдвига ещё влезает в int16 только с запасом, поэтому
 * финальное сложение делаем локальным int32 (регистры) + sat16.
 * После второй секции сигнал всё равно масштабируется вниз — см. п.3.
 */

/* --- 3) Главная защита от «тишины»: насыщение вместо wrap-around --------
 *
 * Замените в sdr_rx_00 / sdr_rx_03 / sdr_rx_04 / sdr_rx_07 записи вида
 *   x = (a + (b + c) * 3 + d) >> M_SR;
 * на
 *   x = sat16((int32_t)a + ((int32_t)b + c) * 3 + d >> M_SR);
 * Только локальные int32 — в ОЗУ состояние по-прежнему int16_t.
 * На AVR локальный int32 из int16 операндов компилируется в addadc-цепочку
 * (без __mulsi3, т.к. ×3 = два сдвига+сложения), прирост ~4-6 тактов,
 * зато переполнение больше никогда не инвертирует знак.
 */
