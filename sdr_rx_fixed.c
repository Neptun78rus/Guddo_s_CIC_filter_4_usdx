#include "sdr_rx_fixed.h"

/* =========================================================================
 * uDSC (LGT8F328P) — 32-битный аппаратный умножитель/делитель.
 * Включается битом EUDSC в MCUCSR-подобном регистре управления периферией
 * (см. референс: SYS_CTRL / "uDSC enable"). Ниже — минимальная обвязка;
 * адреса/биты сверить с актуальным референсом LGT8F328P перед прошивкой.
 * ========================================================================= */

#if defined(LGT8F328P)

void uDSC_init(void)
{
    // включить питание/тактирование блока uDSC (регистр зависит от SDK:
    // в Arduino-LGT модуле это #include <lgtbuiltin.h> / enable uDSC)
    REG_DSC_CON = DSC_MODE_MULDIV;
}

int32_t uDSC_mul_i16(int16_t a, int16_t b)
{
    REG_DSC_AL = (uint8_t)(a & 0xFF);
    REG_DSC_AH = (uint8_t)(a >> 8);
    REG_DSC_BL = (uint8_t)(b & 0xFF);
    REG_DSC_BH = (uint8_t)(b >> 8);
    REG_DSC_CON |= DSC_GO;
    while (!(REG_DSC_CON & DSC_READY)) { /* ~несколько тактов */ }
    uint16_t lo = ((uint16_t)REG_DSC_LL) | ((uint16_t)REG_DSC_LH << 8);
    return (int32_t)lo;   // для i16xi16 старшие байты результата не нужны
}

uint16_t uDSC_div_u16(uint16_t num, uint16_t den)
{
    REG_DSC_AL = (uint8_t)(num & 0xFF);
    REG_DSC_AH = (uint8_t)(num >> 8);
    REG_DSC_BL = (uint8_t)(den & 0xFF);
    REG_DSC_BH = (uint8_t)(den >> 8);
    REG_DSC_CON |= DSC_GO;
    while (!(REG_DSC_CON & DSC_READY)) { }
    return ((uint16_t)REG_DSC_LL) | ((uint16_t)REG_DSC_LH << 8);
}

#else
// заглушка для хостовых тестов/старого ATmega
void uDSC_init(void) {}
int32_t uDSC_mul_i16(int16_t a, int16_t b) { return (int32_t)a * b; }
uint16_t uDSC_div_u16(uint16_t n, uint16_t d) { return n / d; }
#endif

